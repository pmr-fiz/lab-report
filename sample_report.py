rb.solution_heading(doc)

CODE = '''def find_max_profit_period(profits):
    max_so_far = float('-inf')
    current_max = 0
    start = best_start = best_end = 0

    for i, x in enumerate(profits):
        if current_max <= 0:
            current_max = x
            start = i
        else:
            current_max += x
        if current_max > max_so_far:
            max_so_far = current_max
            best_start, best_end = start, i

    return max_so_far, profits[best_start:best_end + 1]


daily_profit = [12, -5, 7, 9, -14, 3, 8, -2, 6, -11, 15, 4, -7, 10, 2]
total, period = find_max_profit_period(daily_profit)
print(f"Максимальная сумма прибыли: {total}")
print(f"Период значений: {period}")'''

rb.add_code_block(doc, CODE, language="python")

